//! Build-time helper: generate an `SzErrorCategory` enum + `classify(code)` taxonomy from a
//! Senzing `szerrors.json` file.
//!
//! `szerrors.json` (shipped with every Senzing SDK install) is the single source of truth for
//! Senzing error code -> exception class. This module contains the *generation logic* only; each
//! consumer supplies its own `szerrors.json` path (they may legitimately track different Senzing
//! versions) and calls this from its own `build.rs`, e.g.:
//!
//! ```no_run
//! # use std::path::Path;
//! let out = sz_rust_sdk_ffi::codegen::generate_error_taxonomy(Path::new("szerrors.json")).unwrap();
//! std::fs::write("errors_generated.rs", out).unwrap();
//! ```

use std::collections::BTreeMap;
use std::fmt;
use std::fs;
use std::path::Path;

/// An error generating the error-taxonomy source.
#[derive(Debug)]
pub enum CodegenError {
    /// Failed to read the `szerrors.json` file.
    Io(std::io::Error),
    /// The file was not valid JSON.
    Json(serde_json::Error),
    /// The JSON did not match the expected `szerrors.json` schema.
    Schema(String),
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CodegenError::Io(e) => write!(f, "cannot read szerrors.json: {e}"),
            CodegenError::Json(e) => write!(f, "invalid JSON in szerrors.json: {e}"),
            CodegenError::Schema(msg) => write!(f, "szerrors.json schema error: {msg}"),
        }
    }
}

impl std::error::Error for CodegenError {}

/// Reads `szerrors_json_path`, parses it, and returns generated Rust source text defining:
/// - `SzErrorCategory` — one variant per distinct `"class"` value in the file
/// - `SzErrorCategory::as_class_str()` — the canonical class name (e.g. `"SzBadInputError"`)
/// - `SzErrorCategory::ALL` — every category variant, for exhaustive iteration
/// - `CODES` — `[(i32, SzErrorCategory); N]`, sorted by code
/// - `classify(code: i32) -> SzErrorCategory` — binary search over `CODES`, falling back to the
///   base category for an unknown code
///
/// Callers typically `include!` the returned text from their own `build.rs` (auto-regenerated on
/// every build), or write it to a checked-in file consumed by a manual regeneration script.
pub fn generate_error_taxonomy(szerrors_json_path: &Path) -> Result<String, CodegenError> {
    let text = fs::read_to_string(szerrors_json_path).map_err(CodegenError::Io)?;
    let doc: serde_json::Value = serde_json::from_str(&text).map_err(CodegenError::Json)?;
    let obj = doc
        .as_object()
        .ok_or_else(|| CodegenError::Schema("top-level value is not an object".to_string()))?;

    let mut variant_of: BTreeMap<String, String> = BTreeMap::new();
    let mut entries: Vec<(i32, String)> = Vec::with_capacity(obj.len());

    for (code_key, entry) in obj {
        let code: i32 = code_key.parse().map_err(|_| {
            CodegenError::Schema(format!("non-integer error code key {code_key:?}"))
        })?;
        let class = entry.get("class").and_then(|c| c.as_str()).ok_or_else(|| {
            CodegenError::Schema(format!("entry {code_key} missing string \"class\""))
        })?;
        variant_of
            .entry(class.to_string())
            .or_insert_with(|| variant_ident(class));
        entries.push((code, class.to_string()));
    }
    entries.sort_by_key(|(c, _)| *c);

    let mut out = String::new();
    out.push_str(
        "// @generated by sz_rust_sdk_ffi::codegen::generate_error_taxonomy — DO NOT EDIT.\n\n",
    );
    out.push_str(
        "/// Language-neutral Senzing error category (one per distinct class in szerrors.json).\n",
    );
    out.push_str(
        "/// Consumers map this to their own exception class/variant; the classes stay per-consumer.\n",
    );
    out.push_str("#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]\n");
    out.push_str("pub enum SzErrorCategory {\n");
    for variant in variant_of.values() {
        out.push_str(&format!("    {variant},\n"));
    }
    out.push_str("}\n\n");

    out.push_str("impl SzErrorCategory {\n");
    out.push_str("    /// The canonical szerrors.json class name (e.g. \"SzBadInputError\").\n");
    out.push_str("    pub const fn as_class_str(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for (class, variant) in &variant_of {
        out.push_str(&format!(
            "            SzErrorCategory::{variant} => {class:?},\n"
        ));
    }
    out.push_str("        }\n    }\n\n");
    out.push_str(
        "    /// Every category variant (generated), for exhaustive iteration by consumers that\n",
    );
    out.push_str("    /// must handle one item per category.\n");
    out.push_str(&format!(
        "    pub const ALL: [SzErrorCategory; {}] = [\n",
        variant_of.len()
    ));
    for variant in variant_of.values() {
        out.push_str(&format!("        SzErrorCategory::{variant},\n"));
    }
    out.push_str("    ];\n}\n\n");

    out.push_str(&format!(
        "/// (errorCode, category), sorted by code. Generated from szerrors.json ({} entries).\n",
        entries.len()
    ));
    out.push_str(&format!(
        "pub const CODES: [(i32, SzErrorCategory); {}] = [\n",
        entries.len()
    ));
    for (code, class) in &entries {
        out.push_str(&format!(
            "    ({code}, SzErrorCategory::{}),\n",
            variant_of[class]
        ));
    }
    out.push_str("];\n\n");

    out.push_str(
        "/// Classify a Senzing error code. Unknown codes fall back to the base category.\n",
    );
    out.push_str("pub fn classify(code: i32) -> SzErrorCategory {\n");
    out.push_str("    match CODES.binary_search_by_key(&code, |&(c, _)| c) {\n");
    out.push_str("        Ok(i) => CODES[i].1,\n");
    out.push_str("        Err(_) => SzErrorCategory::Base,\n");
    out.push_str("    }\n}\n");

    Ok(out)
}

/// "SzBadInputError" -> "BadInput"; "SzError" -> "Base".
fn variant_ident(class: &str) -> String {
    let core = class
        .strip_prefix("Sz")
        .unwrap_or(class)
        .strip_suffix("Error")
        .unwrap_or(class);
    if core.is_empty() {
        "Base".to_string()
    } else {
        core.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write_fixture() -> tempfile_path::TempJson {
        tempfile_path::TempJson::new(
            r#"{
                "2": {"code": "SENZ0002", "class": "SzBadInputError", "name": "X", "comment": "c"},
                "5": {"code": "SENZ0005", "class": "SzError", "name": "Y", "comment": "c"},
                "33": {"code": "SENZ0033", "class": "SzNotFoundError", "name": "Z", "comment": "c"}
            }"#,
        )
    }

    mod tempfile_path {
        use std::path::PathBuf;
        use std::sync::atomic::{AtomicU64, Ordering};

        static COUNTER: AtomicU64 = AtomicU64::new(0);

        pub struct TempJson(pub PathBuf);
        impl TempJson {
            pub fn new(contents: &str) -> Self {
                let n = COUNTER.fetch_add(1, Ordering::Relaxed);
                let path = std::env::temp_dir().join(format!(
                    "sz_rust_sdk_ffi_codegen_test_{}_{n}.json",
                    std::process::id()
                ));
                std::fs::write(&path, contents).unwrap();
                TempJson(path)
            }
        }
        impl Drop for TempJson {
            fn drop(&mut self) {
                let _ = std::fs::remove_file(&self.0);
            }
        }
    }

    #[test]
    fn generates_expected_shape() {
        let fixture = write_fixture();
        let out = generate_error_taxonomy(&fixture.0).unwrap();
        assert!(out.contains("pub enum SzErrorCategory"));
        assert!(out.contains("BadInput,"));
        assert!(out.contains("Base,"));
        assert!(out.contains("NotFound,"));
        assert!(out.contains("pub const CODES: [(i32, SzErrorCategory); 3]"));
        assert!(out.contains("(2, SzErrorCategory::BadInput)"));
        assert!(out.contains("(5, SzErrorCategory::Base)"));
        assert!(out.contains("(33, SzErrorCategory::NotFound)"));
        assert!(out.contains("pub fn classify(code: i32) -> SzErrorCategory"));
    }

    #[test]
    fn rejects_non_object_top_level() {
        let fixture = tempfile_path::TempJson::new("[]");
        let result = generate_error_taxonomy(&fixture.0);
        assert!(matches!(result, Err(CodegenError::Schema(_))));
    }

    #[test]
    fn rejects_missing_class_field() {
        let fixture = tempfile_path::TempJson::new(r#"{"2": {"code": "SENZ0002"}}"#);
        let result = generate_error_taxonomy(&fixture.0);
        assert!(matches!(result, Err(CodegenError::Schema(_))));
    }
}
