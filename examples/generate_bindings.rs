//! Regenerates `src/bindings.rs` from an installed Senzing SDK's C headers using bindgen.
//!
//! House convention: bindgen is run MANUALLY and the output is CHECKED IN (the C ABI is stable, so
//! build-time regeneration isn't warranted). Run after upgrading to a new Senzing SDK version:
//!     cargo run --example generate_bindings

use std::env;
use std::path::{Path, PathBuf};

fn find_senzing_sdk_path() -> Option<PathBuf> {
    if let Ok(path) = env::var("SENZING_SDK_PATH") {
        let p = PathBuf::from(&path);
        if p.exists() {
            println!("Using SENZING_SDK_PATH: {path}");
            return Some(p);
        }
        eprintln!("Warning: SENZING_SDK_PATH set but path doesn't exist: {path}");
    }

    if let Ok(senzing_dir) = env::var("SENZING_DIR") {
        let p = PathBuf::from(&senzing_dir);
        if p.exists() {
            println!("Using SENZING_DIR: {senzing_dir}");
            return Some(p);
        }
    }

    for candidate in [
        "/opt/homebrew/opt/senzing/er", // macOS Homebrew official cask (ARM)
        "/usr/local/opt/senzing/er",    // macOS Homebrew official cask (Intel)
        "/opt/senzing/er",              // Linux standard
    ] {
        let p = PathBuf::from(candidate);
        if p.exists() {
            println!("Found Senzing SDK at: {}", p.display());
            return Some(p);
        }
    }

    None
}

fn main() {
    let sdk_path = find_senzing_sdk_path().expect(
        "Could not find Senzing SDK. Set SENZING_SDK_PATH environment variable or install the SDK.",
    );

    let include_path = sdk_path.join("sdk/c");
    let helpers_path = include_path.join("szhelpers");

    let headers = [
        "libSz.h",
        "libSzConfig.h",
        "libSzConfigMgr.h",
        "libSzDiagnostic.h",
        "libSzProduct.h",
        "szhelpers/SzLang_helpers.h",
    ];

    // Wrapper TU that pulls in every Senzing header (no temp file needed).
    let mut wrapper = String::new();
    for h in &headers {
        let p = include_path.join(h);
        assert!(p.exists(), "header not found: {}", p.display());
        wrapper.push_str(&format!(
            "#include \"{}\"\n",
            p.canonicalize().unwrap().display()
        ));
    }

    let bindings = bindgen::Builder::default()
        .header_contents("wrapper.h", &wrapper)
        .clang_arg(format!(
            "-I{}",
            include_path.canonicalize().unwrap().display()
        ))
        .clang_arg(format!(
            "-I{}",
            helpers_path.canonicalize().unwrap().display()
        ))
        // Union of both prior consumers' allowlists — protects against a future header addition
        // falling outside either one's original narrower/broader pattern.
        .allowlist_function("Sz.*")
        .allowlist_function("G2.*")
        .allowlist_type("Sz.*")
        .allowlist_type("ExportHandle")
        .allowlist_var("SZ_.*")
        .derive_debug(true)
        .derive_default(true)
        .derive_copy(true)
        .use_core()
        .ctypes_prefix("libc")
        .layout_tests(false)
        .generate_comments(true)
        .raw_line("// @generated by `cargo run --example generate_bindings` — DO NOT EDIT.")
        .raw_line("// Regenerate after upgrading to a new Senzing SDK version.")
        .generate()
        .expect("bindgen failed to generate bindings");

    let out = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/bindings.rs");
    bindings.write_to_file(&out).expect("write src/bindings.rs");

    // Edition 2024 requires `unsafe extern` blocks. bindgen 0.72 already emits `unsafe extern "C"`
    // natively; only patch plain `extern "C" {` (older bindgen) to avoid a doubled `unsafe unsafe`.
    let text = std::fs::read_to_string(&out).unwrap();
    let fixed = text.replace("\nextern \"C\" {", "\nunsafe extern \"C\" {");
    std::fs::write(&out, fixed).unwrap();

    println!("wrote {}", out.display());
}
